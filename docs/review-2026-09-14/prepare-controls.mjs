import { execFileSync } from 'node:child_process';
import { readFileSync, writeFileSync, mkdirSync } from 'node:fs';
import { fileURLToPath } from 'node:url';
const root = fileURLToPath(new URL('../../', import.meta.url));
const here = fileURLToPath(new URL('./generated/', import.meta.url));
mkdirSync(here, { recursive: true });
const old = (path) => execFileSync('git', ['show', `72fec82:${path}`], { cwd: root, encoding: 'utf8' });
writeFileSync(here + 'harness-old.ts', old('client/e2e/harness.ts'), 'utf8');
const remap = (source, harness) => source.replaceAll("'./harness.js'", `'${harness}'`).replaceAll("'./fixtures/", "'../../../client/e2e/fixtures/");
writeFileSync(here + 'harness-negative.spec.ts', remap(readFileSync(root + 'client/e2e/harness.spec.ts', 'utf8'), './harness-old.js'), 'utf8');
writeFileSync(here + 'debt-old.spec.ts', remap(old('client/e2e/run-status.spec.ts'), '../../../client/e2e/harness.js'), 'utf8');
